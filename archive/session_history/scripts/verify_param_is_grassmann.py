"""
验证用户的洞察：参数化是否把问题变成了 P？

【核心区分】
  1. 参数化的**表示**层：给定 (J,Θ) 生成 L / 验证 L  —— 显然是 P
  2. 参数化的**搜索**层：找 (J,Θ) 使条件成立        —— 不显然

【关键洞察（本脚本要验证）】
  P1 说：当 J 遍历所有 k-子集、Θ 遍历 R^{k×(s-k)} 时，
        Y_J(Θ) 表示 R^s 中**所有** k 维行空间。
  => {(J,Θ)} 是 Grassmann 流形 Gr(k,s) 的**图卡覆盖**，不是
     "离散选择 J × 连续参数 Θ" 的独立组合。

  维数校验：
     Gr(k,s) 的维数 = k(s-k)
     每个图卡的自由度 = k(s-k)（Θ 的参数个数）
     图卡个数 = C(s,k)
  => 完全匹配：枚举 J 是**图卡切换**，不是必需的分支。

  因此：搜索 (J,Θ)  ≡  在 Gr(k,s) 上找一点，
        不需要枚举 C(s,k) 个分支！
"""
from math import comb

import numpy as np

rng = np.random.default_rng(20260118)


print("=" * 78)
print("1. 维数校验：(J,Θ) 是 Gr(k,s) 的图卡覆盖")
print("=" * 78)
print()
print(f"{'s':>4} {'k':>4} | {'dim Gr(k,s) = k(s-k)':>22} | {'Θ 的参数数':>12} | {'图卡数 C(s,k)':>14}")
print("-" * 78)
for s in (4, 6, 8, 10, 20, 40):
    for k in (1, s // 2, s - 1):
        if k < 1 or k > s - 1:
            continue
        dimG = k * (s - k)
        nTheta = k * (s - k)
        nchart = comb(s, k)
        flag = "  ✓" if dimG == nTheta else "  ✗"
        print(f"{s:>4} {k:>4} | {dimG:>22} | {nTheta:>12} | {nchart:>14,}{flag}")
print()
print("  => 每张图卡的自由度 = Gr(k,s) 的维数；图卡数 = C(s,k)。")
print("     所以 (J,Θ) 是**图卡坐标**，枚举 J 只是换图卡，不是必需的分支。")

print()
print("=" * 78)
print("2. 关键推论：搜索 (J,Θ) ≡ 在 Gr(k,s) 上找一点")
print("=" * 78)
print("""
  P1 原话（§V-A）：
    "as J ranges over all k-element subsets of {1,...,s} and Θ ranges over
     R^{k×(s-k)}, the matrices Y_J(Θ) represent ALL k-dimensional row spaces
     in R^s."

  即  ∪_{J,Θ} {Y_J(Θ)} = Gr(k,s)  （作为集合）

  =>  ∃(J,Θ) 使条件成立   ⟺   ∃R ∈ Gr(k,s) 使条件成立
  =>  **不需要枚举 C(s,k) 个 J**

  这把 §5.4 中"sum_k C(s,k) 的指数规模"直接消掉了！
""")

print()
print("=" * 78)
print("3. 那么问题剩下什么？")
print("=" * 78)
print("""
  剩下的唯一问题是：
     **在 Gr(k,s) 上，判定 (A)∧(S) 的解集是否非空。**

  这是一个 Grassmann 流形上的代数集判定问题。其复杂度取决于该解集的几何性质：

  | 解集性质                | 判定方法           | 复杂度        |
  |-------------------------|--------------------|---------------|
  | 开集（Zariski-开）且非空 | 随机取一点         | **BPP**       |
  | 闭集                     | 代数几何 / 结式    | 通常更难      |
  | 局部闭（开∩闭）          | 需要更细的分析     | 未知          |

  **这正是 0/1 现象的意义**：
    若每阶的 (S) 解集"全有或全无"（数值 62/62），
    则每阶只需**单点检验** => 整个 nu_min 的判定是 **BPP**。
""")

print()
print("=" * 78)
print("4. 逐阶搜索的总规模（修正版）")
print("=" * 78)
print("""
  【未利用参数化图卡性质时】
     sum_{k} C(s,k)    -> 指数级

  【利用参数化图卡性质后】
     每个阶只需在 Gr(k,s) 上取**一点** => 每阶 O(1) 次检验
     总规模 = (n0 - p - q0 + 1) 次单点检验  -> **多项式**

  代价：每次检验需要在 Gr(k,s) 上随机取点并验证 (A)∧(S)。
       后者是多项式（秩计算 + gcd 判据）。
""")

